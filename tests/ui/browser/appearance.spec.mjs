import {test, expect} from "@playwright/test";

test("appearance is lesson-only, preserves light shell, and never resets lesson state", async ({page})=>{
  await page.route("**/*",route=>{const u=new URL(route.request().url());return u.origin==="http://127.0.0.1:4173"&&!u.pathname.startsWith("/api/")?route.continue():route.abort()});
  await page.emulateMedia({colorScheme:null});
  await page.goto("/?demoFallback=1");
  const root=page.locator("html");
  const mode=page.locator("[data-appearance-select]:visible");
  const assertLight=async()=>{
    await expect(root).toHaveCSS("color-scheme","light");
    await expect(root).not.toHaveAttribute("data-theme","dark");
    await expect(page.locator("body")).not.toHaveCSS("background-color","rgb(33, 33, 33)");
  };
  await expect(root).toHaveAttribute("data-lesson-theme","dark");
  await expect(mode).toHaveCount(0);
  await assertLight();
  const originalBody=await page.locator("body").evaluate(el=>getComputedStyle(el).backgroundColor);
  await page.locator("[data-nav-about]").first().click();
  await expect(page.locator(".about-standard")).toBeVisible();
  await expect(mode).toHaveCount(0);
  await assertLight();
  await page.locator("[data-nav-home]").first().click();
  await expect(page.locator("body")).toHaveCSS("background-color",originalBody);
  await page.locator("[data-component-id='catalog.course-card']").first().click();
  await expect(mode).toHaveCount(0);
  await page.locator("[data-start-learning]").click();
  await expect(mode).toHaveValue("dark");
  const frame=page.locator(".lesson-frame");
  const original=await frame.elementHandle();
  const sandbox=await frame.getAttribute("sandbox");
  const child=await original.contentFrame();
  await child.locator("body").waitFor();
  await child.evaluate(()=>{window.__appearanceTestState=37});
  await expect(frame).toHaveCSS("color-scheme","dark");
  await expect.poll(()=>child.evaluate(()=>matchMedia("(prefers-color-scheme: dark)").matches)).toBe(true);
  const sidebar=page.locator(".player-sidebar");
  const toolbar=page.locator(".player-toolbar");
  const sidebarBg=await sidebar.evaluate(el=>getComputedStyle(el).backgroundColor);
  const toolbarBg=await toolbar.evaluate(el=>getComputedStyle(el).backgroundColor);
  await page.getByRole("button",{name:"Zoom in lesson"}).click();
  const reset=page.getByRole("button",{name:"Reset lesson zoom to 100%"});
  await expect(reset).toHaveText("110%");
  await mode.selectOption("light");
  await expect(root).toHaveAttribute("data-lesson-theme","light");
  await expect(frame).toHaveCSS("color-scheme","light");
  await expect.poll(()=>child.evaluate(()=>matchMedia("(prefers-color-scheme: light)").matches)).toBe(true);
  await expect(reset).toHaveText("110%");
  await expect(sidebar).toHaveCSS("background-color",sidebarBg);
  await expect(toolbar).toHaveCSS("background-color",toolbarBg);
  await assertLight();
  expect(await original.evaluate(n=>n===document.querySelector(".lesson-frame"))).toBe(true);
  expect(await child.evaluate(()=>window.__appearanceTestState)).toBe(37);
  expect(await frame.getAttribute("sandbox")).toBe(sandbox);
  await mode.selectOption("system");
  await page.emulateMedia({colorScheme:"dark"});
  await expect(root).toHaveAttribute("data-lesson-theme","dark");
  await expect.poll(()=>child.evaluate(()=>matchMedia("(prefers-color-scheme: dark)").matches)).toBe(true);
  await assertLight();
  await page.emulateMedia({colorScheme:"light"});
  await expect(root).toHaveAttribute("data-lesson-theme","light");
  await mode.selectOption("dark");
  await page.reload();
  await expect(root).toHaveAttribute("data-lesson-theme","dark");
  await assertLight();
});
