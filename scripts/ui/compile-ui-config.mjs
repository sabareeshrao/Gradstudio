import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const configRoot = path.join(repositoryRoot, "static", "ui-config");
const checkOnly = process.argv.includes("--check");

const definitions = [
  ["site", "site.json", "site.schema.json"],
  ["navigation", "navigation.json", "navigation.schema.json"],
  ["home", "home.json", "home.schema.json"],
  ["footer", "footer.json", "footer.schema.json"],
  ["theme", "theme.json", "theme.schema.json"],
  ["registry", "registry.json", "registry.schema.json"]
];

const ajv = new Ajv2020({ allErrors: true, strict: true });
addFormats(ajv);

const loaded = {};
for (const [name, configFile, schemaFile] of definitions) {
  const schema = readJson(path.join(configRoot, "schemas", schemaFile));
  const value = readJson(path.join(configRoot, configFile));
  const validate = ajv.compile(schema);
  if (!validate(value)) {
    const details = ajv.errorsText(validate.errors, { separator: "\n  " });
    throw new Error(`${configFile} does not match ${schemaFile}:\n  ${details}`);
  }
  loaded[name] = value;
}

validateUnique(loaded.navigation.items, "navigation item", (item) => item.componentId);
validateUnique(loaded.navigation.items, "navigation order", (item) => item.order);
validateUnique(loaded.footer.links, "footer link", (item) => item.componentId);
validateUnique(loaded.footer.links, "footer order", (item) => item.order);
validateUnique(loaded.home.blocks, "homepage block", (item) => item.componentId);
validateUnique(loaded.home.blocks, "homepage block order", (item) => item.order);

const visibleRoutes = new Set(loaded.navigation.items.filter((item) => item.visible).map((item) => item.route));
for (const route of ["home", "courses", "about", "contact"]) {
  if (!visibleRoutes.has(route)) throw new Error(`navigation.json must retain visible ${route} navigation`);
}
const coursesItem = loaded.navigation.items.find((item) => item.route === "courses");
if (coursesItem?.kind !== "menu-button") throw new Error("The courses navigation entry must remain a menu-button");

const breakpoints = loaded.theme.breakpoints;
if (!(breakpoints.mobile < breakpoints.compact && breakpoints.compact <= breakpoints.tablet && breakpoints.tablet < breakpoints.wide)) {
  throw new Error("theme breakpoints must be ordered mobile < compact <= tablet < wide");
}

const componentEntries = Object.entries(loaded.registry.components);
for (const [key, component] of componentEntries) {
  if (key !== component.componentId) throw new Error(`registry key ${key} does not match componentId ${component.componentId}`);
  for (const relativePath of [...component.source, component.styleOwner, component.behaviorOwner, ...(component.configPaths || [])]) {
    const absolutePath = path.join(repositoryRoot, relativePath);
    if (!fs.existsSync(absolutePath)) throw new Error(`${component.componentId} references missing path ${relativePath}`);
  }
}

const logoPath = path.join(repositoryRoot, "static", loaded.site.brand.logoSrc);
if (!fs.existsSync(logoPath)) throw new Error(`site brand logo does not exist: ${loaded.site.brand.logoSrc}`);

rejectExecutableConfiguration(loaded);

const runtimeBundle = stableObject({
  schemaVersion: 1,
  site: stripSchema(loaded.site),
  navigation: stripSchema(loaded.navigation),
  home: stripSchema(loaded.home),
  footer: stripSchema(loaded.footer),
  theme: stripSchema(loaded.theme)
});
const runtimeSource = `/* Generated by scripts/ui/compile-ui-config.mjs. Do not edit directly. */\n(function () {\n  const value = ${JSON.stringify(runtimeBundle, null, 2)};\n  function deepFreeze(input) {\n    if (!input || typeof input !== \"object\" || Object.isFrozen(input)) return input;\n    Object.values(input).forEach(deepFreeze);\n    return Object.freeze(input);\n  }\n  window.__GRADSTUDIO_UI_CONFIG__ = deepFreeze(value);\n})();\n`;
const runtimePath = path.join(configRoot, "generated", "ui-config.runtime.js");

const canonicalHtmlPath = path.join(repositoryRoot, "static", "index.html");
const previewHtmlPath = path.join(repositoryRoot, "static", "gradstudio-learn-demo.html");
const canonicalHtml = fs.readFileSync(canonicalHtmlPath, "utf8");
const previewHtml = canonicalHtml
  .replace("<!doctype html>", "<!doctype html>\n<!-- Generated from static/index.html by scripts/ui/compile-ui-config.mjs. -->")
  .replace('class="brand" href="/"', 'class="brand" href="gradstudio-learn-demo.html"');

emit(runtimePath, runtimeSource);
emit(previewHtmlPath, previewHtml);

console.log(`UI configuration ${checkOnly ? "verified" : "compiled"}: ${componentEntries.length} registered components.`);

function emit(targetPath, expected) {
  if (checkOnly) {
    if (!fs.existsSync(targetPath) || fs.readFileSync(targetPath, "utf8") !== expected) {
      throw new Error(`${path.relative(repositoryRoot, targetPath)} is stale; run npm run ui:compile`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, expected, "utf8");
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function stripSchema(value) {
  const { $schema, ...rest } = value;
  return rest;
}

function stableObject(value) {
  if (Array.isArray(value)) return value.map(stableObject);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stableObject(value[key])]));
}

function validateUnique(items, label, keyOf) {
  const seen = new Set();
  for (const item of items) {
    const key = String(keyOf(item));
    if (seen.has(key)) throw new Error(`Duplicate ${label}: ${key}`);
    seen.add(key);
  }
}

function rejectExecutableConfiguration(value) {
  const prohibited = /(?:<\s*script\b|javascript\s*:|data\s*:\s*text\/html|on[a-z]+\s*=)/i;
  const visit = (input, trail) => {
    if (typeof input === "string" && prohibited.test(input)) {
      throw new Error(`Executable content is prohibited in UI configuration at ${trail}`);
    }
    if (Array.isArray(input)) input.forEach((entry, index) => visit(entry, `${trail}[${index}]`));
    else if (input && typeof input === "object") Object.entries(input).forEach(([key, entry]) => visit(entry, `${trail}.${key}`));
  };
  visit(value, "config");
}
